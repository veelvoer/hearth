//! scripts/build-mcpkit.js: packs desktop/relay/mcpkit/* into desktop/relay/mcpkit-files.js.
use anyhow::Result;
use serde_json::{Map, Value};
use std::path::Path;

/// The exact text of mcpkit-files.js for the files in `dir` (sorted by name, JSON with one-space indent, like JSON.stringify(x, null, 1)).
pub fn packed_text(dir: &Path) -> Result<(String, Vec<String>)> {
    let mut names: Vec<String> = std::fs::read_dir(dir)?.flatten().map(|e| e.file_name().to_string_lossy().to_string()).collect();
    names.sort_by(|a, b| a.encode_utf16().cmp(b.encode_utf16()));   // JS sort(): by UTF-16 code units
    let mut out = Map::new();
    for n in &names { out.insert(n.clone(), Value::String(std::fs::read_to_string(dir.join(n))?)); }
    let mut buf = Vec::new();
    {
        use serde::Serialize;
        let f = serde_json::ser::PrettyFormatter::with_indent(b" ");
        let mut ser = serde_json::Serializer::with_formatter(&mut buf, f);
        Value::Object(out).serialize(&mut ser)?;
    }
    Ok((format!("'use strict';\n/* Generated by scripts/build-mcpkit.js from desktop/relay/mcpkit/. Do not edit. */\nmodule.exports = {};\n", String::from_utf8(buf)?), names))
}
pub fn build(root: &Path) -> Result<String> {
    let (text, names) = packed_text(&root.join("desktop/relay/mcpkit"))?;
    std::fs::write(root.join("desktop/relay/mcpkit-files.js"), text)?;
    Ok(format!("Packed {}", names.join(", ")))
}
pub fn is_current(root: &Path) -> Result<bool> {
    let (text, _) = packed_text(&root.join("desktop/relay/mcpkit"))?;
    Ok(std::fs::read_to_string(root.join("desktop/relay/mcpkit-files.js")).map(|t| t == text).unwrap_or(false))
}
