//! Attach to the JVM, reach the activity, turn Java exceptions into errors.

use jni::objects::{JClass, JObject};
use jni::{JNIEnv, JavaVM};
use std::sync::atomic::{AtomicBool, Ordering};

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("Android context is not ready")]
    NoContext,
    #[error("java: {0}")]
    Java(String),
    #[error("{0}")]
    Other(String),
}

static READY: AtomicBool = AtomicBool::new(false);

pub(crate) fn mark_ready() {
    READY.store(true, Ordering::Release);
}

pub fn ready() -> bool {
    READY.load(Ordering::Acquire)
}

/// Run `f` with an attached JNIEnv and the activity (as a Context). Local references are freed afterwards;
/// a pending Java exception becomes `Error::Java(<toString>)`.
pub fn with_env<R>(f: impl FnOnce(&mut JNIEnv, &JObject) -> jni::errors::Result<R>) -> crate::Result<R> {
    if !ready() {
        return Err(Error::NoContext);
    }
    let cx = ndk_context::android_context();
    let vm = unsafe { JavaVM::from_raw(cx.vm().cast()) }.map_err(|e| Error::Java(e.to_string()))?;
    let mut env = vm.attach_current_thread().map_err(|e| Error::Java(e.to_string()))?;
    let activity = unsafe { JObject::from_raw(cx.context().cast()) };
    let r = env.with_local_frame(64, |env| f(env, &activity));
    r.map_err(|e| describe(&mut env, e))
}

/// Turn a JNI error into our error, clearing and describing a pending exception.
pub fn describe(env: &mut JNIEnv, e: jni::errors::Error) -> Error {
    if env.exception_check().unwrap_or(false) {
        let msg = env
            .exception_occurred()
            .ok()
            .and_then(|ex| {
                let _ = env.exception_clear();
                let s = env.call_method(&ex, "toString", "()Ljava/lang/String;", &[]).ok()?.l().ok()?;
                env.get_string(&s.into()).ok().map(String::from)
            })
            .unwrap_or_else(|| e.to_string());
        let _ = env.exception_clear();
        return Error::Java(msg);
    }
    Error::Java(e.to_string())
}

/// Load an app or library class (not a framework class) through the activity's class loader. A plain
/// `FindClass` from a native thread cannot see them.
pub fn load_class<'a>(env: &mut JNIEnv<'a>, ctx: &JObject, dotted: &str) -> jni::errors::Result<JClass<'a>> {
    let cl = env.call_method(ctx, "getClassLoader", "()Ljava/lang/ClassLoader;", &[])?.l()?;
    let name = env.new_string(dotted)?;
    let c = env.call_method(&cl, "loadClass", "(Ljava/lang/String;)Ljava/lang/Class;", &[(&name).into()])?.l()?;
    Ok(JClass::from(c))
}

/// The package name of the app.
pub fn package_name() -> crate::Result<String> {
    with_env(|env, ctx| {
        let s = env.call_method(ctx, "getPackageName", "()Ljava/lang/String;", &[])?.l()?;
        Ok(String::from(env.get_string(&s.into())?))
    })
}

/// `getSystemService(name)` as a local object.
pub(crate) fn system_service<'a>(env: &mut JNIEnv<'a>, ctx: &JObject, name: &str) -> jni::errors::Result<JObject<'a>> {
    let n = env.new_string(name)?;
    env.call_method(ctx, "getSystemService", "(Ljava/lang/String;)Ljava/lang/Object;", &[(&n).into()])?.l()
}

/// The app's vector icon `ic_stat` (generated by hearth-pack), or the platform info icon when absent.
pub(crate) fn icon_id(env: &mut JNIEnv, ctx: &JObject) -> jni::errors::Result<i32> {
    let res = env.call_method(ctx, "getResources", "()Landroid/content/res/Resources;", &[])?.l()?;
    let n = env.new_string("ic_stat")?;
    let t = env.new_string("drawable")?;
    let pkg = env.call_method(ctx, "getPackageName", "()Ljava/lang/String;", &[])?.l()?;
    let id = env
        .call_method(&res, "getIdentifier", "(Ljava/lang/String;Ljava/lang/String;Ljava/lang/String;)I", &[(&n).into(), (&t).into(), (&pkg).into()])?
        .i()?;
    Ok(if id != 0 { id } else { 0x0108_0077 })
}

/// True when the system is in dark mode (uiMode night flag of the current configuration).
pub fn dark_mode() -> bool {
    with_env(|env, ctx| {
        let res = env.call_method(ctx, "getResources", "()Landroid/content/res/Resources;", &[])?.l()?;
        let cfg = env.call_method(&res, "getConfiguration", "()Landroid/content/res/Configuration;", &[])?.l()?;
        let ui = env.get_field(&cfg, "uiMode", "I")?.i()?;
        Ok(ui & 0x30 == 0x20)
    })
    .unwrap_or(true)
}
