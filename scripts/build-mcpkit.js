#!/usr/bin/env node
'use strict';
/* The MCP server starter kit lives as normal files in desktop/relay/mcpkit/ (easy to read and test). Servers only receive the top-level .js files of the relay,
   so this packs the kit into desktop/relay/mcpkit-files.js. Run after changing the kit:  node scripts/build-mcpkit.js   (the test fails when it is out of date) */
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'desktop', 'relay', 'mcpkit'), out = {};
for (const f of fs.readdirSync(dir).sort()) out[f] = fs.readFileSync(path.join(dir, f), 'utf8');
fs.writeFileSync(path.join(__dirname, '..', 'desktop', 'relay', 'mcpkit-files.js'), `'use strict';\n/* Generated by scripts/build-mcpkit.js from desktop/relay/mcpkit/. Do not edit. */\nmodule.exports = ${JSON.stringify(out, null, 1)};\n`);
console.log('Packed ' + Object.keys(out).join(', '));
