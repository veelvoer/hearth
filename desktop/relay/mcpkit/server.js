#!/usr/bin/env node
'use strict';
/* A tiny MCP server (stdio, no dependencies). It reads the tools from ./tools.js and answers Claude's calls.
   Do not edit this file: put your tools in tools.js. Everything this program prints on stdout must be protocol messages, so log to stderr. */
const { execFile } = require('child_process');
const path = require('path');
const tools = require(path.join(__dirname, 'tools.js'));
const log = (...a) => process.stderr.write(a.join(' ') + '\n');

/** Helpers for tools.js */
const helpers = {
  /** Runs a program without a shell (so nothing in [args] can be run as a command). Resolves { code, out, err }. */
  exec: (cmd, args = [], opt = {}) => new Promise((resolve) => execFile(cmd, args.map(String), { timeout: opt.timeout || 60000, maxBuffer: 16e6, cwd: opt.cwd, env: { ...process.env, ...(opt.env || {}) } },
    (e, out, err) => resolve({ code: e ? (typeof e.code === 'number' ? e.code : 1) : 0, out: String(out || ''), err: String(err || (e && e.code === 'ENOENT' ? cmd + ' is not installed or not in PATH' : '') ) }))),
  /** A JSON call to a web API. Headers with secrets come from the environment, never from the code. */
  http: async (url, { method = 'GET', headers = {}, body, timeout = 30000 } = {}) => {
    const r = await fetch(url, { method, headers: { 'Content-Type': 'application/json', ...headers }, body: body === undefined ? undefined : (typeof body === 'string' ? body : JSON.stringify(body)), signal: AbortSignal.timeout(timeout) });
    const text = await r.text(); let json = null; try { json = JSON.parse(text); } catch { /* not json */ }
    return { status: r.status, ok: r.ok, json, text };
  },
  env: (name, why) => { const v = process.env[name]; if (!v) throw new Error(`${name} is not set. ${why || 'Add it to the environment of this MCP server (claude mcp add ... -e ' + name + '=...).'}`); return v; },
};

const send = (o) => process.stdout.write(JSON.stringify(o) + '\n');
const asContent = (r) => {
  if (r && typeof r === 'object' && Array.isArray(r.content)) return r;
  const text = typeof r === 'string' ? r : JSON.stringify(r === undefined ? 'done' : r, null, 2);
  return { content: [{ type: 'text', text: text.length > 200000 ? text.slice(0, 200000) + '\n[cut: too long]' : text }] };
};
const list = () => tools.map((t) => ({ name: t.name, description: t.description, inputSchema: t.inputSchema || { type: 'object', properties: {} }, ...(t.annotations ? { annotations: t.annotations } : {}) }));

async function call(name, args) {
  const t = tools.find((x) => x.name === name);
  if (!t) return { content: [{ type: 'text', text: 'Unknown tool: ' + name }], isError: true };
  for (const k of (t.inputSchema && t.inputSchema.required) || []) if (args[k] === undefined || args[k] === null || args[k] === '') return { content: [{ type: 'text', text: `Missing "${k}". ${t.description}` }], isError: true };
  try { return asContent(await Promise.race([t.run(args, helpers), new Promise((_, no) => setTimeout(() => no(new Error('The tool took longer than ' + ((t.timeoutMs || 120000) / 1000) + ' seconds.')), t.timeoutMs || 120000))])); }
  catch (e) { return { content: [{ type: 'text', text: 'Error: ' + (e && e.message ? e.message : String(e)) }], isError: true }; }
}

let buf = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (d) => {
  buf += d; let i;
  while ((i = buf.indexOf('\n')) >= 0) {
    const line = buf.slice(0, i).trim(); buf = buf.slice(i + 1); if (!line) continue;
    let m; try { m = JSON.parse(line); } catch { continue; }
    if (m.method === 'initialize') send({ jsonrpc: '2.0', id: m.id, result: { protocolVersion: (m.params && m.params.protocolVersion) || '2024-11-05', capabilities: { tools: {} }, serverInfo: { name: path.basename(__dirname), version: '1.0.0' } } });
    else if (m.method === 'tools/list') send({ jsonrpc: '2.0', id: m.id, result: { tools: list() } });
    else if (m.method === 'tools/call') call(m.params && m.params.name, (m.params && m.params.arguments) || {}).then((result) => send({ jsonrpc: '2.0', id: m.id, result }));
    else if (m.method === 'ping') send({ jsonrpc: '2.0', id: m.id, result: {} });
    else if (m.id !== undefined && m.method) send({ jsonrpc: '2.0', id: m.id, error: { code: -32601, message: 'Method not found: ' + m.method } });
  }
});
process.stdin.on('end', () => process.exit(0));
process.on('uncaughtException', (e) => log('problem (kept running):', e.message));
process.on('unhandledRejection', (e) => log('problem (kept running):', e && e.message));
